<?php
// One-time web installer: creates the database tables, config/config.php and the first teacher account.
declare(strict_types=1);
define('INSTALLER', true);
require __DIR__ . '/src/bootstrap.php';

if (is_file(APP_ROOT . '/config/config.php')) {
    http_response_code(403);
    exit('Already installed. To reinstall, delete config/config.php first.');
}

$f = [
    'site_name' => 'Weekly Recap', 'school_domains' => '', 'timezone' => 'Europe/Oslo',
    'db_host' => 'localhost', 'db_name' => '', 'db_user' => '', 'db_pass' => '',
    'from_email' => '', 'smtp_host' => '', 'smtp_port' => '587', 'smtp_secure' => 'tls', 'smtp_user' => '', 'smtp_pass' => '',
    't_name' => '', 't_email' => '',
];
$errors = [];
$manualConfig = null;

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    csrf_check();
    foreach ($f as $k => $_) {
        $f[$k] = trim((string)($_POST[$k] ?? ''));
    }
    $tPass = (string)($_POST['t_pass'] ?? '');

    if ($f['db_name'] === '' || $f['db_user'] === '') {
        $errors[] = 'Database name and user are required.';
    }
    if ($f['t_name'] === '' || !filter_var($f['t_email'], FILTER_VALIDATE_EMAIL) || strlen($tPass) < 10) {
        $errors[] = 'Teacher account: enter a name, a valid email and a password of at least 10 characters.';
    }
    if (!in_array($f['timezone'], DateTimeZone::listIdentifiers(), true)) {
        $errors[] = 'Unknown timezone.';
    }

    if (!$errors) {
        $domains = array_values(array_filter(array_map(
            fn($d) => ltrim(strtolower(trim($d)), '@'), preg_split('/[\s,;]+/', $f['school_domains']))));
        $config = [
            'base_url' => app_url(),
            'site_name' => $f['site_name'] ?: 'Weekly Recap',
            'timezone' => $f['timezone'],
            'trust_proxy' => false,
            'school_domains' => $domains,
            'db' => ['host' => $f['db_host'] ?: 'localhost', 'name' => $f['db_name'], 'user' => $f['db_user'], 'pass' => $f['db_pass']],
            'mail' => [
                'from_email' => $f['from_email'] ?: $f['t_email'],
                'from_name' => $f['site_name'] ?: 'Weekly Recap',
                'smtp_host' => $f['smtp_host'], 'smtp_port' => (int)$f['smtp_port'],
                'smtp_secure' => $f['smtp_secure'], 'smtp_user' => $f['smtp_user'], 'smtp_pass' => $f['smtp_pass'],
            ],
        ];
        $GLOBALS['CONFIG'] = array_merge($GLOBALS['CONFIG'], $config);
        date_default_timezone_set($f['timezone']);

        try {
            $pdo = db();
            $existing = $pdo->query("SHOW TABLES LIKE 'teachers'")->fetch();
            if ($existing) {
                $errors[] = 'This database already contains Weekly Recap tables. Use an empty database or remove them first.';
            } else {
                $sql = (string)file_get_contents(APP_ROOT . '/sql/schema.sql');
                $sql = preg_replace('/^\s*--.*$/m', '', $sql);
                foreach (array_filter(array_map('trim', explode(';', $sql))) as $stmt) {
                    $pdo->exec($stmt);
                }
                q('INSERT INTO teachers (name, email, password_hash, created_at) VALUES (?,?,?,?)',
                    [$f['t_name'], normalize_email($f['t_email']), password_hash($tPass, PASSWORD_DEFAULT), date('Y-m-d H:i:s')]);
                $teacherId = (int)$pdo->lastInsertId();

                $php = "<?php\n// Generated by install.php\nreturn " . var_export($config, true) . ";\n";
                if (@file_put_contents(APP_ROOT . '/config/config.php', $php) === false) {
                    $manualConfig = $php; // folder not writable: show it so it can be uploaded by hand
                } else {
                    @chmod(APP_ROOT . '/config/config.php', 0640);
                    session_regenerate_id(true);
                    $_SESSION['teacher_id'] = $teacherId;
                    $_SESSION['teacher_seen'] = time();
                    flash('Installed! Add your logo and colors under Settings, then create your first test.', 'ok');
                    redirect('admin/');
                }
            }
        } catch (Throwable $e) {
            $errors[] = 'Database error: ' . $e->getMessage();
        }
    }
}

$checks = [
    'PHP 8.0 or newer' => PHP_VERSION_ID >= 80000,
    'PDO MySQL extension' => extension_loaded('pdo_mysql'),
    'config/ folder writable' => is_writable(APP_ROOT . '/config'),
    'uploads/ folder writable (logo)' => is_writable(APP_ROOT . '/uploads'),
];

login_header('Install');
?>
<style>.login{width:560px}.login-card input,.login-card select{font-size:16px;min-height:36px}.login-card h2{font-size:15px;margin:20px 0 8px}</style>
<?php foreach ($errors as $err): ?><div class="login-msg"><?= e($err) ?></div><?php endforeach; ?>
<?php if ($manualConfig !== null): ?>
  <div class="login-card">
    <p>The database is ready and your teacher account was created, but <code>config/</code> is not writable.
      Create the file <code>config/config.php</code> with this content, then <a href="<?= e(url('admin/login.php')) ?>">log in</a>:</p>
    <textarea readonly rows="16" style="width:100%;font-family:monospace;font-size:12px"><?= e($manualConfig) ?></textarea>
  </div>
<?php else: ?>
<form method="post" class="login-card">
  <?= csrf_field() ?>
  <p class="login-help">Takes a minute. You need an empty MySQL database (create it in your hosting panel first).</p>
  <?php foreach ($checks as $label => $ok): ?>
    <div class="small"><?= $ok ? '&#10003;' : '&#10007; <b>Problem:</b>' ?> <?= e($label) ?></div>
  <?php endforeach; ?>

  <h2>Site</h2>
  <label>Site name</label><input type="text" name="site_name" value="<?= e($f['site_name']) ?>">
  <label>Student email domain(s), comma separated, e.g. school.no</label>
  <input type="text" name="school_domains" value="<?= e($f['school_domains']) ?>" placeholder="school.example">
  <label>Timezone</label><input type="text" name="timezone" value="<?= e($f['timezone']) ?>">

  <h2>Database</h2>
  <label>Host</label><input type="text" name="db_host" value="<?= e($f['db_host']) ?>">
  <label>Database name</label><input type="text" name="db_name" value="<?= e($f['db_name']) ?>" required>
  <label>User</label><input type="text" name="db_user" value="<?= e($f['db_user']) ?>" required>
  <label>Password</label><input type="password" name="db_pass">

  <h2>Email (optional, can be added later in config/config.php)</h2>
  <label>From address</label><input type="email" name="from_email" value="<?= e($f['from_email']) ?>" placeholder="recap@school.example">
  <label>SMTP host (empty = use the server's built-in mail)</label><input type="text" name="smtp_host" value="<?= e($f['smtp_host']) ?>">
  <label>SMTP port</label><input type="text" name="smtp_port" value="<?= e($f['smtp_port']) ?>">
  <label>Encryption (tls, ssl or empty)</label><input type="text" name="smtp_secure" value="<?= e($f['smtp_secure']) ?>">
  <label>SMTP user</label><input type="text" name="smtp_user" value="<?= e($f['smtp_user']) ?>">
  <label>SMTP password</label><input type="password" name="smtp_pass">

  <h2>Teacher account</h2>
  <label>Name</label><input type="text" name="t_name" value="<?= e($f['t_name']) ?>" required>
  <label>Email</label><input type="email" name="t_email" value="<?= e($f['t_email']) ?>" required>
  <label>Password (min. 10 characters)</label><input type="password" name="t_pass" minlength="10" required>
  <button type="submit">Install</button>
</form>
<?php endif;
login_footer();
